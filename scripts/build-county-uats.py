#!/usr/bin/env python
"""Build app/data/county_uats.json: the UATs (localities) of each county.

Source: core-assets data/geo/siruta-2025.csv (the SIRUTA register). Level 2 rows are UATs;
JUD is the county code, TIP the type (1/4 municipiu, 2 oras, 3 comuna). The corpus
locality values carry the same SIRUTA code, so the page links resolve by SIRUTA.
Read-only on core-assets. Usage: python scripts/build-county-uats.py [--siruta PATH]
"""
import argparse
import json
import re
from pathlib import Path

import pandas as pd

import sys
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from app.services.place_service import slugify  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DEFAULT = Path("/Users/pax/devbox/gov2/core-assets/data/geo/siruta-2025.csv")
OUT = ROOT / "app" / "data" / "county_uats.json"
TYPES = {1: "municipiu", 4: "municipiu", 2: "oras", 3: "comuna"}
SMALL = {"de", "din", "la", "pe", "cu", "sub", "lui", "cel", "in", "ai", "a", "si", "sur", "del"}


def display(denloc: str) -> str:
    s = re.sub(r"^(MUNICIPIUL|ORAŞ|ORAȘ|ORAS)\s+", "", denloc.strip())
    s = s.replace("Ş", "Ș").replace("ş", "ș").replace("Ţ", "Ț").replace("ţ", "ț")

    def word(w, first):
        w = w.lower()
        return w if (w in SMALL and not first) else w[:1].upper() + w[1:]

    out = []
    for i, tok in enumerate(re.split(r"(\s+|-)", s)):
        out.append(tok if (not tok or tok.isspace() or tok == "-") else word(tok, i == 0))
    return "".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--siruta", default=str(DEFAULT))
    a = ap.parse_args()
    s = pd.read_csv(a.siruta)
    counties = s[(s.NIV == 1) & (s.JUD != 40)]
    j = pd.read_csv(Path(a.siruta).with_name("judete.csv"))
    slug_of = {int(r.siruta): slugify(r.nume_ascii) for r in j.itertuples()}
    items = []
    for _, c in counties.iterrows():
        uats = s[(s.NIV == 2) & (s.JUD == c.JUD) & s.TIP.isin(TYPES)]
        for _, u in uats.iterrows():
            items.append({"siruta": int(u.SIRUTA), "name": display(u.DENLOC),
                          "kind": TYPES[int(u.TIP)], "county_slug": slug_of[int(c.SIRUTA)]})
    items.sort(key=lambda x: (x["county_slug"], x["name"]))
    note = ("Generated by scripts/build-county-uats.py from core-assets siruta-2025.csv. "
            "UATs per county; Bucharest has none.")
    OUT.write_text(json.dumps({"_note": note, "items": items}, ensure_ascii=False,
                              separators=(",", ":")) + "\n", encoding="utf-8")
    print(len(items), "UATs ->", OUT)


if __name__ == "__main__":
    main()
